// 十干四化（中州派，依《安星法》口诀）
// 甲廉破武阳，乙机梁紫阴，丙同机昌廉，丁阴同机巨，
// 戊贪阴阳机，己武贪梁曲，庚阳武府同，辛巨阳曲昌，
// 壬梁紫府(辅)武，癸破巨阴贪。
// 注：王亭之中州派 庚年天府化科、戊年太阳化科，与通行本不同；
// 「壬梁紫府武」之「府」按中州派惯例为左辅化科。
// 已用书中金标准命盘验证：丙年（同禄/机权/昌科/廉忌）、庚年（阳禄/武权/府科/同忌）全合。

import type { SihuaType } from '../types';

export interface SihuaEntry {
  star: string;
  type: SihuaType;
}

const SIHUA_TABLE: Record<number, [string, string, string, string]> = {
  0: ['廉贞', '破军', '武曲', '太阳'], // 甲：禄权科忌
  1: ['天机', '天梁', '紫微', '太阴'], // 乙
  2: ['天同', '天机', '文昌', '廉贞'], // 丙
  3: ['太阴', '天同', '天机', '巨门'], // 丁
  4: ['贪狼', '太阴', '太阳', '天机'], // 戊
  5: ['武曲', '贪狼', '天梁', '文曲'], // 己
  6: ['太阳', '武曲', '天府', '天同'], // 庚
  7: ['巨门', '太阳', '文曲', '文昌'], // 辛
  8: ['天梁', '紫微', '左辅', '武曲'], // 壬
  9: ['破军', '巨门', '太阴', '贪狼'], // 癸
};

const TYPES: SihuaType[] = ['禄', '权', '科', '忌'];

export function getSihua(stem: number): SihuaEntry[] {
  return SIHUA_TABLE[stem].map((star, i) => ({ star, type: TYPES[i] }));
}
